import fs from 'node:fs';

// Router + published journal index own route coverage. Preserve existing hreflang blocks.
const origin = 'https://homesprofessional.com';
const router = fs.readFileSync('src/main.tsx', 'utf8');
const routes = [...router.matchAll(/<Route\s+path="([^"*:]+)"\s+element=\{(?!<Navigate)([^\n]+)\}/g)].map(match => match[1]);
const posts = JSON.parse(fs.readFileSync('src/data/journalIndex.json', 'utf8'));
const all = [...new Set([...routes, ...posts.map(post => `/journal/${post.slug}`)])];
const noindex = route => route.startsWith('/thanks/') || route === '/es/gracias/agente';
const pkg = JSON.parse(fs.readFileSync('package.json', 'utf8'));
pkg.reactSnap.include = all;
fs.writeFileSync('package.json', JSON.stringify(pkg, null, 2) + '\n');
const sitemapPath = 'public/sitemap.xml';
const old = fs.readFileSync(sitemapPath, 'utf8');
const blocks = new Map([...old.matchAll(/<url>([\s\S]*?)<\/url>/g)].map(match => [match[1].match(/<loc>([^<]+)<\/loc>/)?.[1], match[0]]));
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n${all.filter(route => !noindex(route)).map(route => blocks.get(origin + route) || `<url><loc>${origin + route}</loc></url>`).join('\n')}\n</urlset>\n`;
fs.writeFileSync(sitemapPath, sitemap);
const redirects = JSON.parse(fs.readFileSync('scripts/route-redirects.json', 'utf8'));
const lines = ['# Generated by scripts/generate-route-assets.mjs; edit router / route-redirects.json.'];
for (const rule of redirects) lines.push(`${rule.from} ${rule.to} ${rule.status}${rule.force ? '!' : ''}`);
// Explicit route rewrites serve HTML before fallback, with no forced wildcard shadowing.
for (const route of all.filter(route => route !== '/')) lines.push(`${route} ${route}/index.html 200`, `${route}/ ${route}/index.html 200`);
lines.push('/journal/* /404.html 404', '/assets/* /404.html 404', '/images/* /404.html 404', '/videos/* /404.html 404', '/* /index.html 200');
fs.writeFileSync('public/_redirects', lines.join('\n') + '\n');
console.log(`Generated ${all.length} prerender routes and ${all.filter(route => !noindex(route)).length} sitemap URLs.`);
